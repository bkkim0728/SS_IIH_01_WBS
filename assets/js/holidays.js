export const HOLIDAY_MAP = new Map(HOLIDAYS.map(h => [h.date, h]));
export const HOLIDAY_SET = new Set(HOLIDAYS.map(h => h.date));

const YEARS = [...new Set(HOLIDAYS.map(h => +h.date.slice(0, 4)))].sort((a, b) => a - b);
export const FIRST_YEAR = YEARS[0];
export const LAST_YEAR  = YEARS[YEARS.length - 1];

/** 그 날짜의 공휴일 정보. 공휴일이 아니면 null */
export function getHoliday(date){ return HOLIDAY_MAP.get(date) || null; }

/** 그 해의 공휴일 자료를 가지고 있는지 */
export function hasHolidayData(year){ return year >= FIRST_YEAR && year <= LAST_YEAR; }

/** 주말이 아닌 공휴일만. 실제로 영업일을 깎는 날들입니다. */
export function weekdayHolidays(){
  return HOLIDAYS.filter(h => {
    const d = new Date(h.date + 'T00:00:00').getDay();
    return d !== 0 && d !== 6;
  });
}
